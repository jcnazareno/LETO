#!/usr/bin/env python3
"""Generate reproducible GMAT R2026a lunar study scripts; standard library only."""
from __future__ import annotations
import argparse
import ctypes as ct
import datetime as dt
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def initial_state(c, altitude):
    """Rotate position AND inertial velocity vectors, not a rotating-frame state.

    GMAT bundles CSPICE in libGmatBase. Its exported f2c STR2ET entry is used
    because this distribution does not export the str2et_c wrapper. No external
    Python SPICE package is required. J2000 in SPICE is ICRF-aligned here.
    """
    g = Path(c['gmat_root'])
    s = ct.CDLL(str(g/'bin/libGmatBase.so.R2026a'))
    s.erract_c.argtypes = [ct.c_char_p, ct.c_int, ct.c_char_p]
    s.erract_c(b'SET', 0, b'RETURN')
    s.furnsh_c.argtypes = [ct.c_char_p]
    s.failed_c.restype = ct.c_int
    s.getmsg_c.argtypes = [ct.c_char_p, ct.c_int, ct.c_char_p]
    def check():
        if s.failed_c():
            buf = ct.create_string_buffer(3000)
            s.getmsg_c(b'LONG', len(buf), buf)
            s.reset_c()
            raise RuntimeError(buf.value.decode())
    inputs = [g/'data/time/SPICELeapSecondKernel.tls',
              g/'data/planetary_coeff/SPICELunaCurrentKernel.bpc',
              g/'data/planetary_coeff/SPICELunaFrameKernel.tf']
    for p in inputs:
        s.furnsh_c(str(p).encode()); check()
    utc = dt.datetime.fromisoformat(c['epoch_utc'])
    stamp = utc.strftime('%Y %b %d %H:%M:%S UTC').encode()
    et = ct.c_double()
    s.str2et_.argtypes = [ct.c_char_p, ct.POINTER(ct.c_double), ct.c_int]
    s.str2et_(stamp, ct.byref(et), len(stamp)); check()
    mat = (ct.c_double * 9)()
    s.pxform_c.argtypes = [ct.c_char_p, ct.c_char_p, ct.c_double, ct.POINTER(ct.c_double)]
    s.pxform_c(b'MOON_PA_DE421', b'J2000', et.value, mat); check()
    rot = [list(mat)[i:i+3] for i in (0, 3, 6)]
    lon = math.radians(c['initial_node_longitude_pa_deg'])
    r = c['moon_radius_km'] + altitude
    speed = math.sqrt(c['moon_mu_km3_s2']/r)
    rp = [r*math.cos(lon), r*math.sin(lon), 0.0]
    vp = [0.0, 0.0, speed]
    rotate = lambda x: [sum(row[j]*x[j] for j in range(3)) for row in rot]
    state = rotate(rp) + rotate(vp)
    # A polar orbital plane contains the DE421 lunar spin axis at this epoch.
    normal = [state[1]*state[5]-state[2]*state[4],
              state[2]*state[3]-state[0]*state[5],
              state[0]*state[4]-state[1]*state[3]]
    pole = [row[2] for row in rot]
    inc = math.degrees(math.acos(sum(x*y for x,y in zip(normal,pole))/math.sqrt(sum(x*x for x in normal))))
    assert abs(inc-90.0) < 1e-10
    return state, {'tdb_seconds_past_j2000': et.value, 'rotation_pa_to_icrf': rot,
                   'initial_polar_inclination_deg': inc, 'state_icrf_km_km_s': state,
                   'kernel_sha256': {str(p): sha(p) for p in inputs}}


def build(c, out, name, monitor_days, image_days, *, altitude=None,
          controlled=False, degree=None, area=None, cr=None, check_trigger=False):
    degree = degree or c['gravity_degree']
    area = c['srp_area_m2'] if area is None else area
    cr = c['cr'] if cr is None else cr
    alt = c['monitor_altitude_km'] if altitude is None else altitude
    state, meta = initial_state(c, alt)
    g = Path(c['gmat_root']).resolve()
    run = out/'runs'/name
    run.mkdir(parents=True, exist_ok=True)
    rmoon = c['moon_radius_km']
    mu = c['moon_mu_km3_s2']
    science_mass = c['launch_mass_kg']*math.exp(-c['capture_delta_v_m_s']/(9.80665*c['isp_s']))
    # For standalone low-orbit tests, use the ideal reference lowering mass.
    r1, r2 = rmoon+c['monitor_altitude_km'], rmoon+c['image_altitude_km']
    vt1 = math.sqrt(mu/r1)*(1-math.sqrt(2*r2/(r1+r2)))
    vt2 = math.sqrt(mu/r2)*(math.sqrt(2*r1/(r1+r2))-1)
    if altitude == c['image_altitude_km']:
        science_mass *= math.exp(-(vt1+vt2)*1000/(9.80665*c['isp_s']))
    fuel = science_mass-c['dry_mass_kg']
    assert fuel > 0
    lines = [f'% GMAT R2026a: Option A {name}',
             '% Generated by analysis/gmat_lunar_setup/setup_mission.py.',
             '% Study assumptions; not a selected flight trajectory or a lifetime/coverage demonstration.',
             '% Start: already captured in lunar orbit; launch, cruise, capture and commissioning are excluded.',
             '% Initial plane is exactly polar to DE421 PA at epoch; subsequent plane drift is propagated.',
             '% GRGM900C + DE421 PA are frame-matched. Do not replace with DE430 coefficients silently.',
             '% Stationkeeping, if enabled, is ideal circularization at the CURRENT radius, not altitude/node control.',
             '', 'SolarSystem.EphemerisSource = DE421;',
             f'Luna.Mu = {mu:.14f};', f'Luna.EquatorialRadius = {rmoon};',
             'Luna.Flattening = 0;', 'Luna.RotationDataSource = SPICE;',
             "Luna.SpiceFrameId = 'MOON_PA_DE421';", '',
             'Create CoordinateSystem LunaICRF;', 'LunaICRF.Origin = Luna;', 'LunaICRF.Axes = ICRF;',
             'Create CoordinateSystem LunarEquatorJ2000;', 'LunarEquatorJ2000.Origin = Luna;',
             'LunarEquatorJ2000.Axes = BodyInertial;', '',
             'Create ChemicalTank Fuel;', f'Fuel.FuelMass = {fuel:.14g};',
             'Create Spacecraft SMD;', 'SMD.CoordinateSystem = LunaICRF;',
             'SMD.DateFormat = UTCGregorian;',
             "SMD.Epoch = '"+dt.datetime.fromisoformat(c['epoch_utc']).strftime('%d %b %Y %H:%M:%S.000')+"';",
             'SMD.DisplayStateType = Cartesian;']
    lines += [f'SMD.{key} = {value:.16g};' for key,value in zip(['X','Y','Z','VX','VY','VZ'],state)]
    lines += [f'SMD.DryMass = {c["dry_mass_kg"]};', 'SMD.Tanks = {Fuel};',
              f'SMD.Cr = {cr};', f'SMD.SRPArea = {area};', 'SMD.DragArea = 0;',
              '% Kinematic pointing law only; no closed-loop attitude dynamics or sensor jitter.',
              'SMD.Attitude = NadirPointing;', 'SMD.AttitudeReferenceBody = Luna;',
              'SMD.AttitudeConstraintType = OrbitNormal;',
              'SMD.BodyAlignmentVectorX = 0;', 'SMD.BodyAlignmentVectorY = 0;', 'SMD.BodyAlignmentVectorZ = 1;',
              'SMD.BodyConstraintVectorX = 0;', 'SMD.BodyConstraintVectorY = 1;', 'SMD.BodyConstraintVectorZ = 0;', '',
              'Create ForceModel LunarEnvironment;', 'LunarEnvironment.CentralBody = Luna;',
              'LunarEnvironment.PrimaryBodies = {Luna};',
              'LunarEnvironment.PointMasses = {Earth, Sun, Jupiter, Venus, Mars, Saturn};',
              'LunarEnvironment.Drag = None;', 'LunarEnvironment.SRP = On;',
              'LunarEnvironment.RelativisticCorrection = On;', 'LunarEnvironment.ErrorControl = RSSStep;',
              f'LunarEnvironment.GravityField.Luna.Degree = {degree};',
              f'LunarEnvironment.GravityField.Luna.Order = {degree};',
              f"LunarEnvironment.GravityField.Luna.PotentialFile = '{g}/data/gravity/luna/grgm900c.cof';",
              f"LunarEnvironment.GravityField.Luna.TideFile = '{g}/data/gravity/luna/grgm900c.tide';",
              "LunarEnvironment.GravityField.Luna.TideModel = 'Solid';",
              'LunarEnvironment.SRP.SRPModel = Spherical;', 'LunarEnvironment.SRP.Flux = 1361;',
              'LunarEnvironment.SRP.Nominal_Sun = 149597870.7;',
              '% GMAT uses its built-in conical shadow model; ShadowModel is not script-settable.', 'LunarEnvironment.SRP.ExtraShadowBodies = {Earth};', '',
              'Create Propagator LunarProp;', 'LunarProp.FM = LunarEnvironment;',
              'LunarProp.Type = PrinceDormand78;', 'LunarProp.InitialStepSize = 10;',
              f'LunarProp.Accuracy = {c["accuracy"]};', 'LunarProp.MinStep = 0.001;',
              f'LunarProp.MaxStep = {c["max_step_s"]};', 'LunarProp.MaxStepAttempts = 100;',
              'LunarProp.StopIfAccuracyIsViolated = true;', '',
              'Create DifferentialCorrector LoweringDC;', 'LoweringDC.MaximumIterations = 40;',
              'LoweringDC.ShowProgress = true;', f"LoweringDC.ReportFile = '{run}/targeter.txt';", '']
    for burn in ['Lower1','Lower2','Maintenance']:
        lines += [f'Create ImpulsiveBurn {burn};', f'{burn}.CoordinateSystem = Local;',
                  f'{burn}.Origin = Luna;', f'{burn}.Axes = VNB;',
                  f'{burn}.Element1 = 0;', f'{burn}.Element2 = 0;', f'{burn}.Element3 = 0;',
                  f'{burn}.DecrementMass = true;', f'{burn}.Tank = {{Fuel}};',
                  f'{burn}.Isp = {c["isp_s"]};', f'{burn}.GravitationalAccel = 9.80665;', '']
    lines += ['Create ReportFile History Burns;',
              f"History.Filename = '{run}/history.txt';", 'History.Precision = 16;',
              f"Burns.Filename = '{run}/burns.txt';", 'Burns.Precision = 16;',
              'Create OrbitView LunarView;', 'LunarView.Add = {SMD, Luna};',
              'LunarView.CoordinateSystem = LunaICRF;', 'LunarView.ViewPointReference = Luna;',
              'LunarView.ViewPointVector = [18000 0 8000];', 'LunarView.ViewDirection = Luna;',
              'LunarView.ShowPlot = true;',
              'Create Variable Phase DVtotal DVmaintenance DVlowering BurnDV Hperi Hapo Hrad;',
              'Create Variable NextEpoch NextCheck EndPhase LoopEnd Vr Vt Vmag Vcirc; ',
              'BeginMissionSequence;', 'Phase = 1;', 'DVtotal = 0;', 'DVmaintenance = 0;', 'DVlowering = 0;']

    def snapshot():
        return [f'Hperi = SMD.Luna.RadPer - {rmoon};', f'Hapo = SMD.Luna.RadApo - {rmoon};',
                f'Hrad = SMD.Luna.RMAG - {rmoon};',
                'Report History SMD.ElapsedDays Phase SMD.LunaICRF.X SMD.LunaICRF.Y SMD.LunaICRF.Z '
                'SMD.LunaICRF.VX SMD.LunaICRF.VY SMD.LunaICRF.VZ SMD.Luna.SMA SMD.Luna.ECC '
                'SMD.LunarEquatorJ2000.INC Hrad Hperi Hapo SMD.TotalMass SMD.Fuel.FuelMass DVtotal DVmaintenance DVlowering;']

    def propagate(stop):
        # Stop on a spherical guard and abort the sequence rather than propagate below it.
        return [f'Propagate LunarProp(SMD) {{{stop}, SMD.Luna.RMAG = {rmoon+c["minimum_radius_altitude_km"]}}};',
                f'If SMD.Luna.RMAG < {rmoon+c["minimum_radius_altitude_km"]+0.01}',
                *snapshot(), 'Stop;', 'EndIf;']

    def phase(days):
        block = [f'EndPhase = SMD.A1ModJulian + {days:.12g};', 'LoopEnd = EndPhase - 0.00000001;',
                 f'NextCheck = SMD.A1ModJulian + {c["stationkeeping_check_days"]};',
                 'While SMD.A1ModJulian < LoopEnd',
                 f'NextEpoch = SMD.A1ModJulian + {c["output_interval_s"]/86400:.16g};',
                 'If NextEpoch > EndPhase', 'NextEpoch = EndPhase;', 'EndIf;',
                 *propagate('SMD.A1ModJulian = NextEpoch'), *snapshot()]
        if controlled:
            trigger = 1e-7 if check_trigger else c['stationkeeping_eccentricity_trigger']
            block += ['If SMD.A1ModJulian >= NextCheck', f'If SMD.Luna.ECC > {trigger}',
                      '% Remove radial velocity and circularize at the current radius (ideal VNB impulse).',
                      'Vr = (SMD.LunaICRF.X*SMD.LunaICRF.VX + SMD.LunaICRF.Y*SMD.LunaICRF.VY + SMD.LunaICRF.Z*SMD.LunaICRF.VZ) / SMD.Luna.RMAG;',
                      'Vmag = sqrt(SMD.LunaICRF.VX^2 + SMD.LunaICRF.VY^2 + SMD.LunaICRF.VZ^2);', 'Vt = sqrt(Vmag^2 - Vr^2);',
                      f'Vcirc = sqrt({mu}/SMD.Luna.RMAG);',
                      'Maintenance.Element1 = Vcirc*Vt/Vmag - Vmag;',
                      'Maintenance.Element3 = -Vcirc*Vr/Vmag;',
                      'BurnDV = sqrt(Maintenance.Element1^2 + Maintenance.Element3^2)*1000;',
                      'Maneuver Maintenance(SMD);', 'DVmaintenance = DVmaintenance + BurnDV;',
                      'DVtotal = DVtotal + BurnDV;',
                      'Report Burns SMD.ElapsedDays Phase BurnDV DVtotal DVmaintenance DVlowering SMD.Fuel.FuelMass;',
                      *snapshot(), 'EndIf;',
                      f'NextCheck = SMD.A1ModJulian + {c["stationkeeping_check_days"]};', 'EndIf;']
        return block + ['EndWhile;']

    lines += snapshot() + phase(monitor_days)
    if image_days:
        lines += ['% Lower only from the ACTUAL end-of-monitoring state; never reset the spacecraft.',
                  'Phase = 2;', *propagate('SMD.Luna.Apoapsis'),
                  f'Lower1.Element1 = {-vt1:.14g};',
                  'Target LoweringDC {SolveMode = Solve, ExitMode = DiscardAndContinue};',
                  'Vary LoweringDC(Lower1.Element1 = Lower1.Element1, {Perturbation = 0.00001, Lower = -0.8, Upper = 0.8, MaxStep = 0.1});',
                  'Maneuver Lower1(SMD);',
                  f'Achieve LoweringDC(SMD.Luna.RadPer = {r2}, {{Tolerance = 0.01}});', 'EndTarget;',
                  'BurnDV = abs(Lower1.Element1)*1000;', 'DVlowering = DVlowering + BurnDV;',
                  'DVtotal = DVtotal + BurnDV;',
                  'Report Burns SMD.ElapsedDays Phase BurnDV DVtotal DVmaintenance DVlowering SMD.Fuel.FuelMass;',
                  *snapshot(), *propagate('SMD.Luna.Periapsis'),
                  f'Lower2.Element1 = {-vt2:.14g};',
                  'Target LoweringDC {SolveMode = Solve, ExitMode = DiscardAndContinue};',
                  'Vary LoweringDC(Lower2.Element1 = Lower2.Element1, {Perturbation = 0.00001, Lower = -0.8, Upper = 0.8, MaxStep = 0.1});',
                  'Maneuver Lower2(SMD);',
                  f'Achieve LoweringDC(SMD.Luna.SMA = {r2}, {{Tolerance = 0.01}});', 'EndTarget;',
                  'BurnDV = abs(Lower2.Element1)*1000;', 'DVlowering = DVlowering + BurnDV;',
                  'DVtotal = DVtotal + BurnDV;', 'Phase = 3;',
                  'Report Burns SMD.ElapsedDays Phase BurnDV DVtotal DVmaintenance DVlowering SMD.Fuel.FuelMass;',
                  *snapshot(), *phase(image_days)]
    lines += ['% DV values are actual ideal impulses, not integrated acceleration norms.', *snapshot()]
    script = out/(name+'.script')
    script.write_text('\n'.join(lines)+'\n')
    startup = (g/'bin/gmat_startup_file.txt').read_text()
    startup = re.sub(r'^ROOT_PATH\s*=.*$', f'ROOT_PATH = {g}/', startup, flags=re.M)
    startup = re.sub(r'^OUTPUT_PATH\s*=.*$', f'OUTPUT_PATH = {run}/', startup, flags=re.M)
    startup = re.sub(r'^PERSONALIZATION_FILE\s*=.*$', f'PERSONALIZATION_FILE = {g}/data/gui_config/MyGmat.ini', startup, flags=re.M)
    (out/(name+'.startup.txt')).write_text(startup)
    console = startup.replace('PLUGIN                  = ../plugins/libOpenFramesInterface', '#PLUGIN                  = ../plugins/libOpenFramesInterface').replace('PLUGIN                  = ../plugins/libOVtoOFI', '#PLUGIN                  = ../plugins/libOVtoOFI')
    (out/(name+'.console.startup.txt')).write_text(console)
    meta.update({'name': name, 'script_sha256': sha(script), 'config': c,
                 'degree_order': degree, 'srp_area_m2': area, 'cr': cr,
                 'controlled': controlled, 'artificial_controller_exercise_threshold': check_trigger,
                 'monitor_days': monitor_days, 'image_days': image_days,
                 'science_start_mass_kg': science_mass, 'initial_fuel_kg': fuel,
                 'two_body_lowering_m_s': (vt1+vt2)*1000})
    (out/(name+'.manifest.json')).write_text(json.dumps(meta, indent=2)+'\n')
    return name


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config', type=Path, default=HERE/'config.json')
    p.add_argument('--output', type=Path, default=ROOT/'tmp/gmat_lunar_setup/generated')
    p.add_argument('--force', action='store_true', help='explicitly replace generated scripts, not run outputs')
    args = p.parse_args()
    c = json.loads(args.config.read_text())
    libpath = str(Path(c['gmat_root'])/'bin')
    if libpath not in os.environ.get('LD_LIBRARY_PATH', '').split(':'):
        env = os.environ | {'LD_LIBRARY_PATH': libpath+':'+os.environ.get('LD_LIBRARY_PATH','')}
        os.execve(sys.executable, [sys.executable, str(Path(__file__).resolve()), *sys.argv[1:]], env)
    out = args.output.resolve(); out.mkdir(parents=True, exist_ok=True)
    if (any(out.glob('*.script')) or any((out/'scripts').glob('*.script'))) and not args.force:
        p.error('Scripts already exist. Select another --output or review changes and use --force.')
    if any((out/'scripts').glob('*.script')):
        p.error('Choose a new output folder for generated scripts.')
    generated = []
    for controlled, suffix in [(False,'natural'), (True,'ideal_stationkeeping')]:
        generated.append(build(c,out,'option_a_'+suffix,c['monitor_days'],c['image_days'],controlled=controlled))
    generated.append(build(c,out,'validation_transfer',2,2))
    generated.append(build(c,out,'validation_controller_exercise',3,0,controlled=True,check_trigger=True))
    for altitude, label in [(3000,'high'),(300,'low')]:
        generated.append(build(c,out,'validation_'+label+'_30d',30,0,altitude=altitude))
        for degree in [40,80,120]:
            generated.append(build(c,out,f'convergence_{label}_{degree}',7,0,altitude=altitude,degree=degree))
        for case in c['srp_sensitivity']:
            generated.append(build(c,out,f'srp_{label}_{case["name"]}',7,0,altitude=altitude,area=case['area_m2'],cr=case['cr']))
    tight = dict(c, accuracy=1e-12, max_step_s=30.0)
    generated.append(build(tight,out,'numerics_low_tight',7,0,altitude=300))
    model_files = [Path(c['gmat_root'])/'data/gravity/luna'/x for x in ['grgm900c.cof','grgm900c.tide']]
    model_files += [Path(c['gmat_root'])/'data/planetary_ephem/de/leDE1900.421',
                    args.config.resolve(), Path(__file__).resolve(),
                    Path(c['gmat_root'])/'bin/GmatConsole-R2026a',
                    Path(c['gmat_root'])/'bin/libGmatBase.so.R2026a']
    (out/'model_provenance.json').write_text(json.dumps({'generated': generated,
        'input_sha256': {str(f):sha(f) for f in model_files}, 'config': c},indent=2)+'\n')
    print(f'Generated {len(generated)} scripts in {out}')


if __name__ == '__main__':
    main()
